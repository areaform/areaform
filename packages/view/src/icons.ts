export type IconName = keyof typeof ICON_BODIES;

/** Every icon's name. */
export const iconNames = Object.keys(ICON_BODIES) as IconName[];

const SVG = 'http://www.w3.org/2000/svg';

/**
 * A button icon as an element, `--af-icon-size` across (16px by default). It is hidden from
 * assistive technology, so give its button an `aria-label`.
 */
export function createIcon(name: IconName): SVGSVGElement {
    const svg = document.createElementNS(SVG, 'svg');
    for (const [key, value] of Object.entries(ICON_ATTRIBUTES)) svg.setAttribute(key, value);
    svg.innerHTML = ICON_BODIES[name];
    return svg;
}

/** The attributes every icon's `<svg>` has. */
export const ICON_ATTRIBUTES = {
    class: 'af-icon',
    viewBox: '0 0 24 24',
    fill: 'none',
    stroke: 'currentColor',
    'stroke-width': '2',
    'stroke-linecap': 'round',
    'stroke-linejoin': 'round',
    'aria-hidden': 'true',
    focusable: 'false',
} as const;
